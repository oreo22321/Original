// 書式: "名前(引数): 戻り値 — 説明"  (関数)
//       "名前: 型 — 説明"            (値・プロパティ)

export function parseEntries(list, extra = {}) {
  const out = {}
  for (const line of list) {
    const [head, doc = ''] = line.split(' — ')
    const m = /^([A-Za-z_][\w]*)(\(.*?\))?(?::\s*(.+))?$/.exec(head.trim())
    if (!m) continue
    const [, name, params, ret] = m
    out[name] = params
      ? { kind: 'function', sig: params + (ret ? ': ' + ret : ''), doc, ...extra }
      : { kind: 'value', type: ret || 'any', doc, ...extra }
  }
  return out
}

